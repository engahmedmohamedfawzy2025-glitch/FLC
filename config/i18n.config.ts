export function t(key: string, locale: Locale): string {
  return uiTranslations[locale]?.[key] ?? uiTranslations.en?.[key] ?? key;
}

export function getDir(locale: Locale): 'rtl' | 'ltr' {
  const lang = getLanguageByCode(locale);
  if (lang) return lang.direction;
  return i18nConfig.localeDir[locale] || 'ltr';
}

export function localized(value: Record<string, string> | undefined, locale: Locale): string {
  if (!value) return '';
  return value[locale] || value.en || value.ar || Object.values(value)[0] || '';
}
